// Builds the game's generated scripts.
//  - public/town.js: town-src/*.js (in name order) joined into one scope, the second phase of the 2D game.
//  - public/millbrook3d/engine.js: the parts of the prison engine Millbrook needs (sound, sprites, icons, popups,
//    the Claude connection), cut out of public/index.html so the standalone 3D game stays in step with it.
//  - public/millbrook3d/town3d.js: town-src/*.js plus town3d-src/*.js, which swaps the 2D renderer for a 3D one.
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (...p) => readFile(path.join(here, ...p), "utf8");
async function joinDir(dir){
  const files = (await readdir(path.join(here, dir))).filter((f) => f.endsWith(".js")).sort();
  let out = "";
  for (const f of files) out += `\n// ===== ${dir}/${f} =====\n` + (await read(dir, f)) + "\n";
  return {out, count: files.length};
}
const wrap = (body, note) => `// Generated by build.mjs. ${note}\n(() => {\n"use strict";\n${body}})();\n`;

// 2D town
const town = await joinDir("town-src");
await writeFile(path.join(here, "public", "town.js"), wrap(town.out, "Edit town-src/, then run `npm run build`."));
console.log(`Built public/town.js from ${town.count} files.`);

// standalone engine, cut from the prison game
const html = await read("public", "index.html");
const src = html.match(/<script>([\s\S]*)<\/script>\s*<script src="town.js">/)[1];
const lines = src.split("\n");
const at = (re, from = 0) => { for (let i = from; i < lines.length; i++) if (re.test(lines[i])) return i; throw new Error("engine marker not found: " + re); };
// a top-level function or const block: from its first line to the line where braces balance again
function block(re){
  const s = at(re); let depth = 0, i = s;
  for (; i < lines.length; i++){ for (const ch of lines[i]) { if (ch === "{") depth++; else if (ch === "}") depth--; } if (depth <= 0 && i >= s) break; }
  return lines.slice(s, i + 1).join("\n");
}
const range = (a, b) => lines.slice(at(a), at(b, at(a)) + 1).join("\n");
const parts = [
  range(/^const PAL = /, /^function shuffle|^const shuffle = /),
  range(/^\/\/ =+ SOUND/, /^const sfx = /),
  block(/^function contourAt\(/),
  range(/^\/\/ =+ ITEMS/, /^const iconOf = /),
  range(/^\/\/ =+ V4 ADDITIONS/, /^const STACK_MAX = /).split("\n").filter((l) => !/\bdef\(|^for \(const id of \["kessler"/.test(l)).join("\n"),
  lines[at(/^const SUITS = /)],
  block(/^function drawPerson\(/), block(/^function shade\(/),
  block(/^function toast\(/), "let bannerT = null;", block(/^function banner\(/),
  block(/^function drawHeart\(/), block(/^function drawLock\(/), block(/^function wrap\(/),
  lines[at(/^const opWord = /)], lines[at(/^const relWord = /)], block(/^function slotsOf\(/)
];
const engineSrc = await read("town3d-src", "engine", "engine-tail.js");
const engine = `// Generated by build.mjs from public/index.html and town3d-src/engine/. Do not edit.\n(() => {\n"use strict";\nconst $ = id => document.getElementById(id);\nconst TS = 16, CAP = 6;\n${parts.join("\n")}\n${engineSrc}\n})();\n`;
await mkdir(path.join(here, "public", "millbrook3d"), { recursive: true });
await writeFile(path.join(here, "public", "millbrook3d", "engine.js"), engine);
console.log("Built public/millbrook3d/engine.js.");

// 3D town
const t3 = await joinDir("town3d-src");
await writeFile(path.join(here, "public", "millbrook3d", "town3d.js"), wrap(`window.MILLBROOK_STANDALONE = true;\n${town.out}${t3.out}`, "Edit town-src/ and town3d-src/, then run `npm run build`."));
console.log(`Built public/millbrook3d/town3d.js from ${town.count + t3.count} files.`);

// the 3D page, wearing the prison game's stylesheet so every window and readout looks the same
const style = html.match(/<style>([\s\S]*?)<\/style>/)[1];
const page = (await read("town3d-src", "page.html")).replace("{{STYLE}}", () => style);
await writeFile(path.join(here, "public", "millbrook3d.html"), page);
console.log("Built public/millbrook3d.html.");

// the Halloween edition: the same scripts, switched to Hallowmere before they load
const hcss = await read("town3d-src", "hallow.css");
const hpage = page
  .replace("<title>Millbrook</title>", "<title>Millbrook: Hallowmere</title>")
  .replace("family=Press+Start+2P&family=VT323", "family=Press+Start+2P&family=VT323&family=Pirata+One&family=IM+Fell+English:ital@0;1")
  .replace("</style>", () => hcss + "</style>")
  .replace('<script src="vendor/three.min.js"></script>', '<script>window.MILLBROOK_HALLOW = true;</script>\n<script src="vendor/three.min.js"></script>');
await writeFile(path.join(here, "public", "millbrook-hallow.html"), hpage);
console.log("Built public/millbrook-hallow.html.");
