// Combines town-src/*.js (in name order) into public/town.js, the game's second phase.
// The parts share one scope, so functions in one part can call functions in another.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(here, "town-src");
const files = (await readdir(srcDir)).filter((f) => f.endsWith(".js")).sort();
let out = "// Generated by build.mjs from town-src/. Edit those files, then run `npm run build`.\n(() => {\n\"use strict\";\n";
for (const f of files) out += `\n// ===== ${f} =====\n` + (await readFile(path.join(srcDir, f), "utf8")) + "\n";
out += "})();\n";
await writeFile(path.join(here, "public", "town.js"), out);
console.log(`Built public/town.js from ${files.length} files.`);
